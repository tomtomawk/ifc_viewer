"""Réécriture d'un fichier Revit : conteneur OLE, flux compressés, partitions.

Usage : python -I ecriture.py <source> <sortie> [--blocs-zero] [--signature]
                               [--champ ID CHEMIN VALEUR]
                               [--texte ID ANCIEN NOUVEAU]

Sans option, le fichier est réécrit avec les mêmes flux, octet pour octet, dans un
conteneur OLE produit ici (essai W0). Options d'essai :
  --blocs-zero   met à zéro les CRC des flux compressés (blocs de 353 octets et
                 fin du dernier morceau) : Revit refuse le fichier (essai W1) ;
  --signature    inverse un bit des 64 octets qui suivent le premier document d'une
                 partition (marqueur 0x0F3F), code correcteur recalculé ;
  --texte        remplace ANCIEN par NOUVEAU dans le RTF de la note de texte ID,
                 recalcule l'Adler-32 de l'enregistrement, recompresse son membre,
                 recadre la partition et recalcule le code correcteur (crcbloc.py).

Cadrage d'une partition (LISEZMOI § 7) : u32 9, u32 0, puis pour chaque document un
ContentMarker (classe 0x3A3 : pointeur de ContentKey, nombre d'éléments) suivi de
membres « 28 0F, u32 h2, u32 enregistrements, u32 longueur gzip + 8, u32 somme des
corps, u32 section, u32 0, gzip », chacun suivi de « 21 0F, u32 longueur gzip + 8 »
qui le relie au suivant ; un membre vide clôt le document, puis « 3F 0F, u32 64,
64 octets, u32 34, "Data generated by Autodesk® Revit®" ». La partition se termine
par un ContentMarker sans clé et de nombre −1 (CLOTURE).
"""
import os, struct, sys, zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cfb import CFB
from champs import Lecteur
from crcbloc import decoder_flux, encoder_flux
from extract import DATA, GZIP, PAD

FIN, LIBRE, FATSECT = 0xFFFFFFFE, 0xFFFFFFFF, 0xFFFFFFFD
SS, MSS, SEUIL = 4096, 64, 4096
CLOTURE = bytes.fromhex('a30300000000ffffffff')
EN_TETE_GZIP = bytes.fromhex('1f8b08000000000000 0b'.replace(' ', ''))


def ecrire_cfb(source, sortie, contenus):
    """Écrit un CFB v4 avec l'arborescence de source (mêmes entrées, mêmes liens et
    couleurs, mêmes dates) et, pour chaque flux, le contenu donné ({index d'entrée:
    octets}) ou son contenu d'origine."""
    c = CFB(source)
    h = open(source, 'rb').read(512)
    raw = c.chain_bytes(struct.unpack_from('<I', h, 0x30)[0])
    entrees = [bytearray(raw[i * 128:(i + 1) * 128]) for i in range(len(raw) // 128)]
    flux = {d['i']: contenus.get(d['i'], c.read(d)) for d in c.dirs if d['type'] == 2}

    # mini-flux : flux de moins de 4 096 octets, en mini-secteurs de 64 octets
    mini, minifat, debut = bytearray(), [], {}
    for i, b in sorted(flux.items()):
        if len(b) < SEUIL:
            n = -(-len(b) // MSS)
            debut[i] = len(minifat) if n else FIN
            minifat += [len(minifat) + k + 1 for k in range(n - 1)] + ([FIN] if n else [])
            mini += b + bytes(n * MSS - len(b))
    grands = [(i, b) for i, b in sorted(flux.items()) if len(b) >= SEUIL]

    n_dir = -(-len(entrees) // (SS // 128))
    n_mfat = -(-len(minifat) * 4 // SS)
    n_mini = -(-len(mini) // SS)
    n_grands = sum(-(-len(b) // SS) for _, b in grands)
    n_fat = 1
    while n_fat * (SS // 4) < n_fat + n_dir + n_mfat + n_mini + n_grands:
        n_fat += 1
    assert n_fat <= 109, 'secteurs DIFAT non gérés'

    fat, secteurs = [FATSECT] * n_fat, []

    def chaine(donnees):
        n = -(-len(donnees) // SS)
        s0 = len(fat)
        fat.extend(s0 + k + 1 for k in range(n - 1))
        fat.append(FIN)
        secteurs.append(bytes(donnees) + bytes(n * SS - len(donnees)))
        return s0

    s_dir = chaine(bytes(n_dir * SS))           # réécrit à la fin
    s_mfat = chaine(b''.join(struct.pack('<I', x) for x in minifat)) if minifat else FIN
    s_mini = chaine(mini) if mini else FIN
    for i, b in grands:
        struct.pack_into('<IQ', entrees[i], 116, chaine(b), len(b))
    for i, b in flux.items():
        if len(b) < SEUIL:
            struct.pack_into('<IQ', entrees[i], 116, debut[i], len(b))
    struct.pack_into('<IQ', entrees[0], 116, s_mini, len(mini))
    secteurs[0] = b''.join(entrees) + bytes(n_dir * SS - len(entrees) * 128)

    fat += [LIBRE] * (n_fat * (SS // 4) - len(fat))
    tete = bytearray(SS)
    tete[:8] = bytes.fromhex('d0cf11e0a1b11ae1')
    struct.pack_into('<HHHHH', tete, 0x18, 0x3E, 4, 0xFFFE, 12, 6)
    struct.pack_into('<IIIIIIIII', tete, 0x28, n_dir, n_fat, s_dir, 0, SEUIL, s_mfat, n_mfat, FIN, 0)
    struct.pack_into('<109I', tete, 0x4C, *(list(range(n_fat)) + [LIBRE] * (109 - n_fat)))
    with open(sortie, 'wb') as f:
        f.write(tete)
        f.write(b''.join(struct.pack('<I', x) for x in fat))
        for s in secteurs:
            f.write(s)


def decouper(b):
    """(données, blocs) d'un flux compressé, découpage brut : données sans les blocs
    de 353 octets (fin du flux comprise), et les blocs retirés. Sert à l'essai W1."""
    plein = len(b) // (DATA + PAD)
    donnees = b''.join(b[i:i + DATA] for i in range(0, plein * (DATA + PAD), DATA + PAD))
    blocs = [b[i + DATA:i + DATA + PAD] for i in range(0, plein * (DATA + PAD), DATA + PAD)]
    return donnees + b[plein * (DATA + PAD):], blocs


def blocs_zero(b):
    """Flux dont les blocs de 353 octets et la fin (remplissage et CRC du dernier
    morceau) sont mis à zéro, longueur conservée : Revit le refuse (essai W1)."""
    d = decoder_flux(b)
    u, blocs = decouper(b)
    out = bytearray()
    for k, i in enumerate(range(0, len(u), DATA)):
        out += u[i:i + DATA]
        if k < len(blocs):
            out += bytes(PAD)
    plein = len(blocs) * DATA
    fin = len(d) - plein                      # données utiles du dernier morceau
    out[len(blocs) * (DATA + PAD) + fin:] = bytes(len(out) - len(blocs) * (DATA + PAD) - fin)
    return bytes(out)


def membres(u):
    """Membres d'une partition décodée : [{'pos', 'tete' (32 octets : lien 21 0F ou
    fin du ContentMarker, puis 28 0F et 6 u32), 'gzip', 'donnees'}]."""
    out = []
    for m in GZIP.finditer(u):
        h = m.start()
        d = zlib.decompressobj(31)
        r = d.decompress(u[h:])
        n = len(u) - h - len(d.unused_data)
        out.append({'pos': h, 'tete': u[h - 32:h], 'gzip': u[h:h + n], 'donnees': r})
    return out


def gzip_revit(donnees):
    """Membre gzip comme Revit : en-tête 1F 8B 08 00 00000000 00 0B, deflate brut,
    CRC32 et longueur."""
    c = zlib.compressobj(6, zlib.DEFLATED, -15)
    return EN_TETE_GZIP + c.compress(donnees) + c.flush() + struct.pack('<II', zlib.crc32(donnees), len(donnees) & 0xFFFFFFFF)


def modifier_partition(u, eid, transformer):
    """Partition décodée dont l'enregistrement 0x66 eid est remplacé par
    transformer(corps) ; Adler-32 recalculé, membre recompressé, en-tête et lien
    « 21 0F » suivant mis à jour. Renvoie (partition, écart de longueur du corps)."""
    for m in membres(u):
        if struct.unpack_from('<I', m['tete'], 24)[0] != 0x66:
            continue
        d, o = m['donnees'], 0
        while o + 20 <= len(d):
            e, _, n = struct.unpack_from('<qII', d, o)
            if e == eid:
                break
            o += 20 + n
        else:
            continue
        neuf = transformer(d[o + 16:o + 16 + n])
        d = d[:o] + struct.pack('<qII', eid, zlib.adler32(neuf), len(neuf)) + neuf + struct.pack('<I', len(neuf)) + d[o + 20 + n:]
        gz = gzip_revit(d)
        tete = bytearray(m['tete'])
        struct.pack_into('<II', tete, 16, len(gz) + 8, struct.unpack_from('<I', tete, 20)[0] + len(neuf) - n)
        fin = m['pos'] + len(m['gzip'])
        assert u[fin:fin + 2] == b'\x21\x0f'
        u = u[:m['pos'] - 32] + bytes(tete) + gz + b'\x21\x0f' + struct.pack('<I', len(gz) + 8) + u[fin + 6:]
        return u, len(neuf) - n
    raise SystemExit('enregistrement %d introuvable' % eid)


def enregistrements(d, section):
    """[(position, id, longueur du corps)] des enregistrements d'un membre décodé."""
    out, o, hd = [], 0, 16 if section != 0x65 else 12
    while o + hd <= len(d):
        e = struct.unpack_from('<q', d, o)[0]
        n = struct.unpack_from('<I', d, o + hd - 4)[0]
        out.append((o, e, n))
        o += hd + n + 4
    return out


def cadrer(eid, corps, section):
    """Enregistrement complet : id, Adler-32 (sections 0x66 et 0x67), longueur, corps,
    longueur."""
    milieu = struct.pack('<I', zlib.adler32(corps)) if section != 0x65 else b''
    return struct.pack('<q', eid) + milieu + struct.pack('<I', len(corps)) + corps + struct.pack('<I', len(corps))


def remplacer_membre(u, m, d, n_ajoutes, ecart_corps):
    """Partition où le membre m a pour données d : gzip refait, en-tête (nombre
    d'enregistrements, g + 8, somme des corps) et lien suivant mis à jour."""
    gz = gzip_revit(d)
    tete = bytearray(m['tete'])
    n, _, somme = struct.unpack_from('<III', tete, 12)
    struct.pack_into('<III', tete, 12, n + n_ajoutes, len(gz) + 8, somme + ecart_corps)
    fin = m['pos'] + len(m['gzip'])
    assert u[fin:fin + 2] == b'\x21\x0f'
    return u[:m['pos'] - 32] + bytes(tete) + gz + b'\x21\x0f' + struct.pack('<I', len(gz) + 8) + u[fin + 6:]


def dupliquer(u, sch, source, nouveau, transformer):
    """Partition où l'élément source est copié sous l'id nouveau (en fin du document
    principal, ses ids étant croissants) : en-tête 0x65 (id remplacé dans
    m_parents.m_deletion), objet 0x66 passé par transformer (qui reçoit le corps et
    son id à remplacer), complément 0x67 recopié ; nombre d'éléments du
    ContentMarker principal augmenté de 1."""
    fin_doc = u.find(b'\x3f\x0f\x40\x00\x00\x00')
    for section in (0x65, 0x66, 0x67):
        ms = [m for m in membres(u) if m['pos'] < fin_doc and struct.unpack_from('<I', m['tete'], 24)[0] == section]
        corps = None
        for m in ms:
            for o, e, n in enregistrements(m['donnees'], section):
                if e == source:
                    hd = 16 if section != 0x65 else 12
                    corps = m['donnees'][o + hd:o + hd + n]
        assert corps is not None, 'élément %d absent de la section %x' % (source, section)
        if section == 0x65:
            corps = corps.replace(struct.pack('<q', source), struct.pack('<q', nouveau))
        elif section == 0x66:
            corps = transformer(corps)
        m = ms[-1]
        dernier = enregistrements(m['donnees'], section)[-1][1]
        assert dernier < nouveau, 'ids non croissants'
        u = remplacer_membre(u, m, m['donnees'] + cadrer(nouveau, corps, section), 1, len(corps))
        fin_doc = u.find(b'\x3f\x0f\x40\x00\x00\x00')
    # ContentMarker du document principal : u16 0x3A3, u32 0 (pas de clé), u32 nombre
    assert u[8:14] == b'\xa3\x03\x00\x00\x00\x00'
    return u[:14] + struct.pack('<I', struct.unpack_from('<I', u, 14)[0] + 1) + u[18:]


def table_ajouter(u, source, nouveau):
    """Global/ElemTable décodé (8 octets de préfixe, gzip d'un objet ElemTable) où un
    ElemRec copié de celui de source est ajouté pour l'id nouveau, et
    IdentifierSource.m_last porté à nouveau."""
    corps = zlib.decompressobj(31).decompress(u[8:])
    n = struct.unpack_from('<I', corps, 2)[0]
    recs = [corps[6 + 40 * i:6 + 40 * (i + 1)] for i in range(n)]
    modele = next(r for r in recs if struct.unpack_from('<q', r, 20)[0] == source)
    assert struct.unpack_from('<q', recs[-1], 20)[0] < nouveau
    rec = struct.pack('<q', nouveau) + modele[8:20] + struct.pack('<q', nouveau) + modele[28:]
    corps = corps[:2] + struct.pack('<I', n + 1) + corps[6:6 + 40 * n] + rec + corps[6 + 40 * n:]
    # IdentifierSource (dernier corps de pointeur) : m_last, puis le u32 final du flux
    dernier = struct.unpack_from('<q', corps, len(corps) - 12)[0]
    assert dernier < nouveau, 'm_last %d' % dernier
    corps = corps[:-12] + struct.pack('<q', nouveau) + corps[-4:]
    return u[:8] + gzip_revit(corps), dernier


def schema_de(c):
    """Schéma de classes du fichier ouvert c (Formats/Latest)."""
    from objets import ClassTable, inflate, unpad
    sch = ClassTable(inflate(unpad(c.read(dict(c.tree())['/Formats/Latest']))))
    sch.run()
    return sch


def main():
    a = sys.argv[1:]
    source, sortie = a[0], a[1]
    c = CFB(source)
    contenus = {}
    nouveau = None
    if '--dupliquer' in a:
        # nouvel id : IdentifierSource.m_last + 1 (Global/ElemTable)
        t = decoder_flux(c.read(dict(c.tree())['/Global/ElemTable']))
        corps = zlib.decompressobj(31).decompress(t[8:])
        nouveau = struct.unpack_from('<q', corps, len(corps) - 12)[0] + 1
    for p, d in c.tree():
        if d['type'] != 2:
            continue
        b = c.read(d)
        compresse = p.startswith('/Global/') or p.startswith('/Partitions/') or p in ('/Formats/Latest', '/Contents')
        if not compresse:
            contenus[d['i']] = b
            continue
        if '--blocs-zero' in a:
            contenus[d['i']] = blocs_zero(b)
            continue
        u = decoder_flux(b)
        if '--texte' in a and p.startswith('/Partitions/'):
            i = a.index('--texte')
            eid, ancien, nouveau = int(a[i + 1]), a[i + 2].encode('latin-1'), a[i + 3].encode('latin-1')

            def transformer(corps):
                assert corps.count(ancien) == 1, 'texte %r trouvé %d fois' % (ancien, corps.count(ancien))
                j = corps.index(ancien)
                k = corps.rfind(b'{\\rtf', 0, j)   # m_arrRtfStream : u32 nombre, octets
                n = struct.unpack_from('<I', corps, k - 4)[0]
                rtf = corps[k:k + n].replace(ancien, nouveau)
                return corps[:k - 4] + struct.pack('<I', len(rtf)) + rtf + corps[k + n:]

            u, ecart = modifier_partition(u, eid, transformer)
            print('%s : enregistrement %d modifié (%+d octets)' % (p, eid, ecart))
        if '--champ' in a and p.startswith('/Partitions/'):
            i = a.index('--champ')
            eid, chemin, texte = int(a[i + 1]), a[i + 2], a[i + 3]
            sch = schema_de(c)

            def transformer(corps):
                pos = {}
                Lecteur(sch, corps, positions=pos).element()
                if chemin not in pos:
                    raise SystemExit('champ %s absent (%s…)' % (chemin, ', '.join(list(pos)[:8])))
                o, fmt = pos[chemin]
                v = float(texte) if fmt in ('<f', '<d') else int(texte, 0)
                print('%s : %r -> %r' % (chemin, struct.unpack_from(fmt, corps, o)[0], v))
                return corps[:o] + struct.pack(fmt, v) + corps[o + struct.calcsize(fmt):]

            u, ecart = modifier_partition(u, eid, transformer)
        if '--dupliquer' in a:
            i = a.index('--dupliquer')
            src, texte, dy = int(a[i + 1]), a[i + 2].encode('latin-1'), float(a[i + 3]) / 304.8
            if p == '/Global/ElemTable':
                u, dernier = table_ajouter(u, src, nouveau)
                print('ElemTable : élément %d ajouté (m_last %d -> %d)' % (nouveau, dernier, nouveau))
            elif p == '/Global/DocumentIncrementTable' and '--total' in a:
                # m_totalElements : nombre d'enregistrements de la partition
                h = u.find(b'\x1f\x8b')
                corps = zlib.decompressobj(31).decompress(u[h:])
                pos = {}
                r = Lecteur(schema_de(c), corps, positions=pos)
                r.o = 2
                r.obj(struct.unpack_from('<H', corps)[0])
                cles = [k for k in pos if k.endswith('m_totalElements')]
                for k in cles:
                    o, fmt = pos[k]
                    corps = corps[:o] + struct.pack(fmt, struct.unpack_from(fmt, corps, o)[0] + 1) + corps[o + 4:]
                u = u[:h] + gzip_revit(corps)
                print('DocumentIncrementTable : %d totaux d\'éléments augmentés de 1' % len(cles))
            elif p.startswith('/Partitions/'):
                sch = schema_de(c)

                def transformer(corps):
                    pos = {}
                    Lecteur(sch, corps, positions=pos).element()
                    o, _ = pos['.m_id.m_id.m_id64']
                    corps = corps[:o] + struct.pack('<q', nouveau) + corps[o + 8:]
                    o, _ = pos['.m_orig[1]']
                    corps = corps[:o] + struct.pack('<d', struct.unpack_from('<d', corps, o)[0] + dy) + corps[o + 8:]
                    k = corps.find(b'{\\rtf')       # RTF : remplace le texte du paragraphe
                    n = struct.unpack_from('<I', corps, k - 4)[0]
                    rtf = corps[k:k + n]
                    j = rtf.rfind(b'\\fs')
                    j = rtf.index(b' ', j) + 1
                    rtf = rtf[:j] + texte + rtf[rtf.index(b'\\par', j):]
                    return corps[:k - 4] + struct.pack('<I', len(rtf)) + rtf + corps[k + n:]

                u = dupliquer(u, sch, src, nouveau, transformer)
                print('%s : élément %d copié sous l\'id %d' % (p, src, nouveau))
        if '--signature' in a and p.startswith('/Partitions/'):
            j = u.find(b'\x3f\x0f\x40\x00\x00\x00')
            u = u[:j + 6] + bytes([u[j + 6] ^ 0x01]) + u[j + 7:]
        contenus[d['i']] = encoder_flux(u)
    ecrire_cfb(source, sortie, contenus)
    print('écrit', sortie, os.path.getsize(sortie), 'octets')


if __name__ == '__main__':
    main()
